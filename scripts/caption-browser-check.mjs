import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import path from 'node:path';

const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:960},acceptDownloads:true});
const page=await context.newPage(),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4310');
await page.locator('#fileInput').setInputFiles(path.resolve('.data/test-fixtures/caption-voice.mp4'));
await page.waitForFunction(()=>!document.querySelector('#progressDialog').open,{timeout:60000});
await page.locator('[data-add]').first().click();
await page.locator('#subtitleBtn').click();
await page.waitForSelector('#subtitleDialog[open]');
await page.locator('#subtitleLanguage').selectOption('en');
await page.locator('#subtitleModel').selectOption('tiny');
await page.locator('#generateSubtitles').click();
await page.waitForSelector('#subtitleDialog[open]',{timeout:120000});
assert.ok(await page.locator('.caption-row').count()>0);
const first=page.locator('.caption-row').first();
await first.locator('[data-caption-field="start"]').fill('0');await first.locator('[data-caption-field="start"]').press('Tab');
await first.locator('[data-caption-field="end"]').fill('3');await first.locator('[data-caption-field="end"]').press('Tab');
await first.locator('textarea').fill('버튼으로 수정한 로컬 AI 자막');await first.locator('textarea').press('Tab');
await page.locator('#subtitleFontSize').fill('58');await page.locator('#subtitleFontSize').press('Tab');
await page.locator('#subtitlePosition').fill('84');await page.locator('#subtitlePosition').press('Tab');
const downloadPromise=page.waitForEvent('download');await page.locator('#downloadSrt').click();const download=await downloadPromise;assert.match(download.suggestedFilename(),/\.srt$/);
await page.locator('#closeSubtitles').click();
const ruler=await page.locator('#ruler').boundingBox();await page.mouse.click(ruler.x+30,ruler.y+14);
await page.waitForSelector('#subtitleCue:not([hidden])');
assert.match(await page.locator('#subtitleCue').textContent(),/로컬 AI 자막/);
await page.screenshot({path:'.data/test-fixtures/caption-editor.png'});
await page.locator('#exportBtn').click();await page.waitForSelector('#progressResult a',{timeout:180000});
assert.match(await page.locator('#progressTitle').textContent(),/완성/);
assert.deepEqual(errors,[]);
console.log('PASS browser buttons: import, caption generation, edit, style, SRT download, preview and captioned MP4 export; zero page errors');
await browser.close();
